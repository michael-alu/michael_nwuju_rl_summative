"""
Write docs/ASSUMPTIONS.md from the tags in the config files.

Every setting in configs/market.yaml is commented with a tag: [assumption], [calibrated],
[NGX rule] or DESIGN KNOB. This script lists the settings by tag, so that the doc can not be parted from the config.

Change the working directory to the root of the project: uv run python scripts/write_assumptions.py
"""

from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent

MARKET_CONFIG = PROJECT_ROOT / "configs" / "market.yaml"

HARD_CONFIG = PROJECT_ROOT / "configs" / "market_hard.yaml"

OUTPUT_PATH = PROJECT_ROOT / "docs" / "ASSUMPTIONS.md"


def tagged_settings(config_path: Path, tag: str) -> list[tuple[str, str, str]]:
    settings: list[tuple[str, str, str]] = []

    for line in open(config_path, encoding="utf-8"):
        is_setting = ":" in line and "#" in line and not line.startswith("#") and not line.startswith(" ")

        if not is_setting or tag not in line:
            continue

        setting, comment = line.split("#", 1)

        key, value = setting.split(":", 1)

        settings.append((key.strip(), value.strip(), comment.strip().replace("|", "/")))

    return settings


def table(settings: list[tuple[str, str, str]]) -> list[str]:
    rows = ["| Setting | Value | Note |", "|---|---|---|"]

    for key, value, comment in settings:
        rows.append(f"| `{key}` | {value} | {comment} |")

    return rows


def section(heading: str, config_path: Path, tag: str) -> list[str]:
    settings = tagged_settings(config_path, tag)

    lines = [heading, ""]

    lines = lines + table(settings)

    lines = lines + [""]

    return lines


def main() -> None:
    lines = [
        "# ThinBook Pension: assumptions to verify",

        "",

        "Generated by `scripts/write_assumptions.py` from the tags in `configs/market.yaml`. Do not edit by hand; edit the config and rerun.",

        "",
    ]

    lines = lines + section("## 1. Our assumptions (please verify)", MARKET_CONFIG, "[assumption]")

    lines = lines + section("## 2. Design knobs (set by the structural design checks in scripts/design_checks.py, then frozen)", MARKET_CONFIG, "DESIGN KNOB")

    lines = lines + section("## 3. Real NGX rules and published fees (check they are current)", MARKET_CONFIG, "[NGX rule")

    lines = lines + section("## 4. Calibrated from NGX data (sources and date ranges in configs/calibration.yaml)", MARKET_CONFIG, "[calibrated")

    lines = lines + section("## 5. Hard market for the generalization test (all assumptions)", HARD_CONFIG, "")

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)

    OUTPUT_PATH.write_text("\n".join(lines), encoding="utf-8")

    print(f"Wrote {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
